def _stems(name: str) -> set[str]:
    n = name.lower().strip()
    found = {s for g in GROUPS if any(n.startswith(x) for x in g) for s in g}
    return found or {n[:max(3, len(n) - 1)]}  # unknown name: the name itself, any ending («Зарина» → «Зарин…»)


def is_name(word: str, name: str) -> bool:
    """Is `word` (as written in a message) a form of the person's `name`?"""
    w = word.lower().strip()
    if not w or not name:
        return False
    if w == name.lower().strip():
        return True
    return len(w) >= 2 and any(w.startswith(s) for s in _stems(name))


def leading_name(text: str, name: str):
    """«Женечка, поменяй аватарку» to a partner called Евгения: the rest of the phrase, else None."""
    m = re.match(r"\s*([А-ЯЁа-яёA-Za-z-]+)\s*[,!]\s*(.+)", text, re.S)
    return m[2] if m and is_name(m[1], name) else None
